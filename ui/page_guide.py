"""מסך "הסבר": איך משתמשים בסורק כדי לקבל את התוצאות הכי טובות. כתוב לאדם שלא חזק במחשבים."""
from __future__ import annotations

import streamlit as st

from core.config import load_config
from ui.data_access import edge_cards


def _past_numbers() -> tuple[list[str], int | None, dict]:
    """מה קרה בעבר: אחוז הצלחה לכל תבנית שעברה, ונתוני התיק (כולל רצף ההפסדים הארוך ביותר
    בתיק של עד 5 עסקאות פתוחות, כמו שהיא באמת תסחור)."""
    data = edge_cards() or {}
    lines = []
    for s in data.get("setups", {}).values():
        if not s.get("passed"):
            continue
        win = s.get("walk_forward", {}).get("combined", {}).get("win_rate")
        if win is not None:
            lines.append(f"**{s['name_he']}:** הצליחה בערך ב-{round(win * 10)} מתוך 10 פעמים.")
    book = data.get("portfolio_all_active") or {}
    return lines, book.get("max_losing_streak"), book


